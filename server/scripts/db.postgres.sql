DROP DATABASE IF EXISTS touring;
CREATE DATABASE touring WITH ENCODING 'UTF8';

-- \c is a psql terminal command to switch databases
\c touring

DROP TABLE IF EXISTS performer_fans;
DROP TABLE IF EXISTS tour_stops;
DROP TABLE IF EXISTS performers;
CREATE TABLE performers (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password VARCHAR(255) NOT NULL,
  bio TEXT,
  image_bucket_file_name VARCHAR(255),
  fans_email_content TEXT,
  slug VARCHAR(255) NOT NULL, -- the performer url path
  created_at TIMESTAMP DEFAULT (NOW() AT TIME ZONE 'UTC'),

  CONSTRAINT performers_unique_email UNIQUE (email),
  CONSTRAINT performers_unique_slug UNIQUE (slug)
);
CREATE INDEX idx_performers_name ON performers(name);

CREATE TABLE performer_fans (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fan_email VARCHAR(255) NOT NULL,
  performer_id INT NOT NULL REFERENCES performers(id),

  CONSTRAINT performer_fans_unique_key UNIQUE (fan_email, performer_id)
);

CREATE EXTENSION IF NOT EXISTS postgis;
DROP TABLE IF EXISTS geo_places;
CREATE TABLE geo_places (
  id VARCHAR(255) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  normalized_name VARCHAR(255) NOT NULL,
  country_code VARCHAR(4) NOT NULL,
  country_name VARCHAR(255) NOT NULL,
  usa_state VARCHAR(255),
  -- location is null initially then set in GeoPlacesDataHandler
  location GEOGRAPHY(Point, 4326),
  population INT NOT NULL
);
CREATE INDEX idx_places_location ON geo_places USING GIST (location);

CREATE TABLE tour_stops (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  performer_id INT NOT NULL,
  place_id VARCHAR(255) NOT NULL REFERENCES geo_places(id),
  start_date VARCHAR(255) NOT NULL,
  end_date VARCHAR(255) NOT NULL
);

DROP TABLE IF EXISTS tenant_states CASCADE;
CREATE TABLE tenant_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_token VARCHAR(255) NOT NULL,
  state_name VARCHAR(255) NOT NULL,
  tenant_id VARCHAR(255),
  state_value JSONB NOT NULL,
  expires_at TIMESTAMP NOT NULL,

  CONSTRAINT tenant_states_unique_row UNIQUE (session_token, state_name)
);
CREATE INDEX idx_tenant_states_expires_at ON tenant_states(expires_at);
