import { Criteria } from "./QueryDefs";

export interface JunctionRelation {
    entityTypeId: string,
    /** This is used only if the relation is multiple, and is added in a Where clause, not in JOIN ON. 
     * If not present then it is computed based on the junctionRelation's entity type relation fields.  */
    relationFieldName?: string,
    /** Computed and managed internally */
    relationFieldPath?: string
}
export enum EntityRelationType {
    OneToOne = "OneToOne",
    ManyToOne = "ManyToOne",
    OneToMany = "OneToMany",
    ManyToMany = "ManyToMany"
}
export interface EntityRelationField {
    name: string,
    entityTypeId: string,
    type: EntityRelationType,
    /**
     * If true then the relation entities are cascade deleted.
     */
    parentChild?: true,
    label?: string,
    junctionRelation?: JunctionRelation,
    sourceIdField?: string,
    /** Should not be specified if junctionRelation is specified. */
    targetIdField?: string,
    /** The id field in junctionRelation.entityTypeId referencing the source entity type. This is needed if 
     * junctionRelation is specified. If not present then it is computed based on the junctionRelation's entity type relation fields. */
    junctionSourceIdField?,
    /** Added as WHERE conditions of the junction table. */
    junctionCriteria?: Criteria,
    /** Added in the JOIN ON conditions for single relations, and in the WHERE conditions for multiple relations. */
    targetCriteria?: Criteria,
    /**
     * If the relation is auto generated (to implement many to many for example).
     */
    autoGeneratedInfo?: any
}